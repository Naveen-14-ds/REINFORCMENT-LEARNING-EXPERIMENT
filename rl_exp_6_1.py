import numpy as np
import pandas as pd
epsilon = 0.1
num_trials = 1000
if 'df' in locals():
    num_ads = df.shape[1]
    ctr_data = np.array([0.05, 0.08, 0.12])
    num_ads = len(ctr_data)
else:
    ctr_data = np.array([0.05, 0.08, 0.12])
    num_ads = len(ctr_data)
counts = np.zeros(num_ads)
rewards = np.zeros(num_ads)
for trial in range(num_trials):
    if np.random.rand() < epsilon:
        chosen_ad = np.random.randint(num_ads)
    else:
        average_rewards = np.divide(rewards, counts, out=np.zeros_like(rewards), where=counts!=0)
        chosen_ad = np.argmax(average_rewards)
    if np.random.rand() < ctr_data[chosen_ad]:
        reward = 1
    else:
        reward = 0
    counts[chosen_ad] += 1
    rewards[chosen_ad] += reward
final_average_rewards = np.divide(rewards, counts, out=np.zeros_like(rewards), where=counts!=0)
best_ad = np.argmax(final_average_rewards)
results_data = {
    'Ad': [f'Ad {i}' for i in range(num_ads)],
    'Times Shown': counts,
    'Total Clicks': rewards,
    'Average CTR': final_average_rewards
}
results_df = pd.DataFrame(results_data)
print(f"Simulation completed after {num_trials} trials.")
