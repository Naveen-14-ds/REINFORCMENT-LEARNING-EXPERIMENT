import gym
import numpy as np
np.bool8 = np.bool_
env = gym.make('CartPole-v0')
state = env.reset()
print(f"Action Space: {env.action_space}")
print(f"Observation Space: {env.observation_space}")
def describe_state(state):
    print(f"Cart Position: {state[0]}")
    print(f"Cart Velocity: {state[1]}")
    print(f"Pole Angle: {state[2]}")
    print(f"Pole Angular Velocity: {state[3]}")
print("Initial State:")
describe_state(state)
actions = {0: "Move Left", 1: "Move Right"}
for action in actions:
    print(f"Action {action}: {actions[action]}")
num_steps = 5
print("\nSimulating a few steps:")
for step in range(num_steps):
    action = env.action_space.sample()
    next_state, reward, done, info = env.step(action)
    print(f"\nStep {step + 1}:")
    print(f"Action taken: {actions[action]}")
    print("Next State:")
    describe_state(next_state)
    print(f"Reward: {reward}")
    print(f"Done: {done}")
env.close()

