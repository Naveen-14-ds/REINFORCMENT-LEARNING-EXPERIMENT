import numpy as np
import gymnasium as gym
import random
import pandas as pd
env = gym.make("FrozenLake-v1")
alpha = 0.85
gamma = 0.90
epsilon = 0.8
num_episodes = 5000
num_timesteps = 1000
def random_policy():
    return env.action_space.sample()
v = {s: 0.0 for s in range(env.observation_space.n)}
for i in range(num_episodes):
    s, info = env.reset()
    for t in range(num_timesteps):
        a = random_policy()
        s_, r, terminated, truncated, info = env.step(a)
        done = terminated or truncated
        v[s] += alpha * (r + gamma * v[s_] - v[s])
        s = s_
        if done:
            break
print("TD Prediction:")
print(pd.DataFrame(list(v.items()), columns=["State", "Value"]))
Q = {
    (s, a): 0.0
    for s in range(env.observation_space.n)
    for a in range(env.action_space.n)
}
def epsilon_greedy(state, epsilon):
    if random.random() < epsilon:
        return env.action_space.sample()
    return max(
        range(env.action_space.n),
        key=lambda a: Q[(state, a)]
    )
for i in range(num_episodes):
    s, info = env.reset()
    a = epsilon_greedy(s, epsilon)
    for t in range(num_timesteps):
        s_, r, terminated, truncated, info = env.step(a)
        done = terminated or truncated
        a_ = epsilon_greedy(s_, epsilon)
        target = r if done else r + gamma * Q[(s_, a_)]
        Q[(s, a)] += alpha * (target - Q[(s, a)])
        s = s_
        a = a_
        if done:
            break
print("\nSARSA:")
print(pd.DataFrame(
    [(s, a, value) for (s, a), value in Q.items()],
    columns=["State", "Action", "Q-Value"]
))
for i in range(num_episodes):
    s, info = env.reset()
    for t in range(num_timesteps):
        a = epsilon_greedy(s, epsilon)
        s_, r, terminated, truncated, info = env.step(a)
        done = terminated or truncated
        target = r if done else r + gamma * max(
            Q[(s_, next_a)] for next_a in range(env.action_space.n)
        )
        Q[(s, a)] += alpha * (target - Q[(s, a)])
        s = s_
        if done:
            break
print("\nQ-Learning:")
print(pd.DataFrame(
    [(s, a, value) for (s, a), value in Q.items()],
    columns=["State", "Action", "Q-Value"]
))
env.close()