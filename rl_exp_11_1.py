import random
import gymnasium as gym
env = gym.make("Taxi-v4", render_mode="ansi")
q = {}
for s in range(env.observation_space.n):
    for a in range(env.action_space.n):
        q[(s, a)] = 0.0
def update_q_table(prev_state, action, reward, nextstate, alpha, gamma, done):
    if done:
        qa = 0
    else:
        qa = max(
            q[(nextstate, a)]
            for a in range(env.action_space.n)
        )
    q[(prev_state, action)] += alpha * (
        reward + gamma * qa - q[(prev_state, action)]
    )
def epsilon_greedy_policy(state, epsilon):
    if random.uniform(0, 1) < epsilon:
        return env.action_space.sample()
    return max(
        range(env.action_space.n),
        key=lambda a: q[(state, a)]
    )
alpha = 0.4
gamma = 0.999
epsilon = 0.017
num_episodes = 8000
for i in range(num_episodes):
    total_reward = 0
    prev_state, info = env.reset()
    while True:
        action = epsilon_greedy_policy(prev_state, epsilon)
        nextstate, reward, terminated, truncated, info = env.step(action)
        done = terminated or truncated
        update_q_table(
            prev_state,
            action,
            reward,
            nextstate,
            alpha,
            gamma,
            done
        )
        prev_state = nextstate
        total_reward += reward
        if done:
            break
    print("Episode:", i + 1, "Total reward:", total_reward)
print("\nTraining completed!")
state, info = env.reset()
print(env.render())
while True:
    action = max(
        range(env.action_space.n),
        key=lambda a: q[(state, a)]
    )
    nextstate, reward, terminated, truncated, info = env.step(action)
    state = nextstate
    print(env.render())
    if terminated or truncated:
        print("Final Reward:", reward)
        break
env.close()